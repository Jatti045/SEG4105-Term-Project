-- Smart Inventory Fridge schema.
-- Built from docs/diagrams/erd.json and docs/data-dictionary.md (0.1-draft).
-- Type mapping: int -> integer, string -> text, date -> date,
-- datetime -> timestamptz (UTC), bool -> boolean.
-- Tables are plural snake_case; "user" is reserved in PostgreSQL, so User -> users.

BEGIN;

-- D2 Product Catalog ---------------------------------------------------------

CREATE TABLE categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL
);

CREATE TABLE products (
    product_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id       integer NOT NULL REFERENCES categories (category_id),   -- R1
    name              text    NOT NULL,
    unit              text    NOT NULL,
    unit_weight_g     integer NOT NULL,
    package_weight_g  integer NOT NULL,
    shelf_life_days   integer NOT NULL,
    recognition_label text    NOT NULL,
    -- Removed products keep their history but leave the catalog.
    active            boolean NOT NULL DEFAULT true,
    -- Tile in the food sprite sheet (8 x 8, numbered row by row). Empty for no icon.
    icon              smallint,
    CONSTRAINT products_icon_chk CHECK (icon BETWEEN 0 AND 63),
    -- The recognition model's output must point at exactly one product.
    CONSTRAINT products_recognition_label_uq UNIQUE (recognition_label),
    CONSTRAINT products_package_weight_chk CHECK (package_weight_g >= 0),
    -- The remaining-amount formula divides by (unit_weight_g - package_weight_g).
    CONSTRAINT products_unit_weight_chk    CHECK (unit_weight_g > package_weight_g),
    CONSTRAINT products_shelf_life_chk     CHECK (shelf_life_days >= 0)
);

-- D6 Users -------------------------------------------------------------------

CREATE TABLE users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text    NOT NULL,
    email   text    NOT NULL,
    role    text    NOT NULL,
    active  boolean NOT NULL DEFAULT true,
    CONSTRAINT users_role_chk CHECK (role IN ('manager', 'kitchen_staff', 'purchasing_staff'))
);

-- D1 Inventory ---------------------------------------------------------------

CREATE TABLE fridges (
    fridge_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    location        text NOT NULL,
    status          text NOT NULL DEFAULT 'offline',
    last_reading_at timestamptz,
    -- Position and size on the kitchen floor plan, in plan units (the plan is 1000 x 620).
    plan_x          integer NOT NULL DEFAULT 20,
    plan_y          integer NOT NULL DEFAULT 20,
    plan_w          integer NOT NULL DEFAULT 120,
    plan_h          integer NOT NULL DEFAULT 90,
    CONSTRAINT fridges_status_chk CHECK (status IN ('online', 'offline')),
    CONSTRAINT fridges_plan_chk   CHECK (plan_x >= 0 AND plan_y >= 0 AND plan_w > 0 AND plan_h > 0)
);

CREATE TABLE rows (
    row_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fridge_id        integer NOT NULL REFERENCES fridges (fridge_id),                        -- R6
    product_id       integer REFERENCES products (product_id) ON DELETE SET NULL,            -- R4
    label            text        NOT NULL,
    current_weight_g integer     NOT NULL DEFAULT 0,
    current_count    integer     NOT NULL DEFAULT 0,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT rows_weight_chk CHECK (current_weight_g >= 0),
    CONSTRAINT rows_count_chk  CHECK (current_count >= 0)
);

CREATE TABLE stock_items (
    item_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  integer     NOT NULL REFERENCES products (product_id),   -- R3
    row_id      integer     NOT NULL REFERENCES rows (row_id),           -- R7
    added_at    timestamptz NOT NULL DEFAULT now(),
    expiry_date date        NOT NULL,
    status      text        NOT NULL DEFAULT 'in_stock',
    removed_at  timestamptz,
    CONSTRAINT stock_items_status_chk CHECK (status IN ('in_stock', 'consumed', 'wasted', 'removed')),
    -- removed_at is empty while in stock, and set once the item leaves.
    CONSTRAINT stock_items_removed_at_chk CHECK ((status = 'in_stock') = (removed_at IS NULL))
);

-- D3 Alert Settings ----------------------------------------------------------

CREATE TABLE alert_thresholds (
    product_id          integer PRIMARY KEY REFERENCES products (product_id) ON DELETE CASCADE,  -- R2
    low_stock_threshold integer     NOT NULL,
    expiry_warning_days integer     NOT NULL,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT alert_thresholds_low_stock_chk CHECK (low_stock_threshold >= 0),
    CONSTRAINT alert_thresholds_expiry_chk    CHECK (expiry_warning_days >= 0)
);

CREATE TABLE notification_preferences (
    preference_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,  -- R12
    alert_type    text    NOT NULL,
    channel       text    NOT NULL,
    enabled       boolean NOT NULL DEFAULT true,
    CONSTRAINT notification_preferences_alert_type_chk CHECK (alert_type IN ('expiry', 'low_stock', 'stock_mismatch')),
    CONSTRAINT notification_preferences_channel_chk    CHECK (channel IN ('email', 'dashboard')),
    CONSTRAINT notification_preferences_uq UNIQUE (user_id, alert_type, channel)
);

-- D4 Stock History -----------------------------------------------------------

CREATE TABLE waste_records (
    waste_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     integer     NOT NULL REFERENCES stock_items (item_id),  -- R8
    user_id     integer     REFERENCES users (user_id),                 -- R10; empty = system-detected
    reason      text        NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    -- R8: a stock item has at most one waste record.
    CONSTRAINT waste_records_item_uq    UNIQUE (item_id),
    CONSTRAINT waste_records_reason_chk CHECK (reason IN ('expired', 'spoiled', 'damaged', 'other'))
);

CREATE TABLE stock_snapshots (
    snapshot_date date        NOT NULL,
    product_id    integer     NOT NULL REFERENCES products (product_id),  -- R13
    quantity      integer     NOT NULL,
    recorded_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (snapshot_date, product_id),
    CONSTRAINT stock_snapshots_quantity_chk CHECK (quantity >= 0)
);

-- D5 Alerts ------------------------------------------------------------------

CREATE TABLE alerts (
    alert_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer     NOT NULL REFERENCES products (product_id),  -- R5
    item_id    integer     REFERENCES stock_items (item_id),           -- R9
    row_id     integer     REFERENCES rows (row_id),                   -- R14
    alert_type text        NOT NULL,
    status     text        NOT NULL DEFAULT 'active',
    raised_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT alerts_alert_type_chk CHECK (alert_type IN ('expiry', 'low_stock', 'stock_mismatch')),
    CONSTRAINT alerts_status_chk     CHECK (status IN ('active', 'cleared')),
    -- Expiry alerts point at the expiring item; other types have no item.
    CONSTRAINT alerts_item_chk CHECK ((alert_type = 'expiry') = (item_id IS NOT NULL)),
    -- Stock mismatch alerts point at the row whose reading is off; other types have no row.
    CONSTRAINT alerts_row_chk  CHECK ((alert_type = 'stock_mismatch') = (row_id IS NOT NULL))
);

-- Indexes on foreign keys and common lookups ---------------------------------

CREATE INDEX products_category_id_idx         ON products (category_id);
CREATE INDEX rows_fridge_id_idx               ON rows (fridge_id);
CREATE INDEX rows_product_id_idx              ON rows (product_id);
CREATE INDEX stock_items_product_id_idx       ON stock_items (product_id);
CREATE INDEX stock_items_row_id_idx           ON stock_items (row_id);
CREATE INDEX stock_items_in_stock_expiry_idx  ON stock_items (expiry_date) WHERE status = 'in_stock';
CREATE INDEX waste_records_user_id_idx        ON waste_records (user_id);
CREATE INDEX stock_snapshots_product_id_idx   ON stock_snapshots (product_id);
CREATE INDEX alerts_product_id_idx            ON alerts (product_id);
CREATE INDEX alerts_item_id_idx               ON alerts (item_id);
CREATE INDEX alerts_row_id_idx                ON alerts (row_id);
CREATE INDEX alerts_active_idx                ON alerts (raised_at) WHERE status = 'active';

-- At most one active alert of each kind per thing, even when checks run at the same time:
-- per row for stock mismatches, per item for expiry, per product for low stock.
CREATE UNIQUE INDEX alerts_one_active_mismatch_per_row
    ON alerts (row_id) WHERE status = 'active' AND alert_type = 'stock_mismatch';
CREATE UNIQUE INDEX alerts_one_active_expiry_per_item
    ON alerts (item_id) WHERE status = 'active' AND alert_type = 'expiry';
CREATE UNIQUE INDEX alerts_one_active_low_stock_per_product
    ON alerts (product_id) WHERE status = 'active' AND alert_type = 'low_stock';

COMMIT;
